// Another build (or another game) can be smaller or lay out its pages differently: a guard
// outside the image or on an unreadable page is a mismatch, never a crash (fail closed).
bool Readable(const uint8_t* p) {
    __try {
        volatile uint8_t b = *p;
        (void)b;
        return true;
    } __except (EXCEPTION_EXECUTE_HANDLER) {
        return false;
    }
}
bool GuardMatches(const uint8_t* p, const uint8_t* guard, size_t n) {
    __try {
        return std::memcmp(p, guard, n) == 0;
    } __except (EXCEPTION_EXECUTE_HANDLER) {
        return false;
    }
}
