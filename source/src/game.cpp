std::wstring IniPath() {
    wchar_t exe[MAX_PATH];
    GetModuleFileNameW(nullptr, exe, MAX_PATH);
    std::wstring s = exe;
    return s.substr(0, s.find_last_of(L"\\/")) + L"\\b2svr.ini";
}
bool IniFlag(const wchar_t* key) {
    wchar_t v[16];
    GetPrivateProfileStringW(L"b2svr", key, L"off", v, 16, IniPath().c_str());
    return _wcsicmp(v, L"on") == 0 || _wcsicmp(v, L"force") == 0;
}
