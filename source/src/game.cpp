// Exact guard bytes hold only on the analysed build: they include RIP displacements, which differ in
// every other build (LIVE Steam demo: "CINEMA guards MISMATCH", the letterbox fix stayed off). On any
// other build the address came from sigdb, whose signature already matched the code with those
// fields wildcarded, so a readable address passes.
bool GuardAt(uintptr_t address, const uint8_t* guard, size_t n) {
    if (!address) return false;
    if (g_known) return GuardMatches(reinterpret_cast<const uint8_t*>(address), guard, n);
    return Readable(reinterpret_cast<const uint8_t*>(address));
}

bool ResolveAll(const char* textSha256, bool log) {
    g_base = reinterpret_cast<uintptr_t>(GetModuleHandleW(nullptr));
    const bool forceScan = IniFlag(L"signature_scan");        // b2svr.ini: signature_scan=force
    const bool verifiedOnly = IniFlag(L"verified_build_only");  // b2svr.ini: verified_build_only=on
    g_known = textSha256 && std::strcmp(textSha256, kVerifiedTextSha) == 0 && !forceScan;
    if (log) {
        if (g_known) Log("Game build: VERIFIED (addresses recorded for this exact build)");
        else Log("Game build: UNVERIFIED (.text %s) - addresses are found by signature%s", textSha256 ? textSha256 : "?",
                 forceScan ? " (signature scan forced)" : "");
    }
    if (!g_known && verifiedOnly) {
        if (log) Log("verified_build_only=on and this build is not the verified one: mod disabled");
        return false;
    }
    sigdb::Resolve(g_known, log);
    g_resolvedAnchors = 0;
    for (size_t i = 0; i < size_t(Anchor::Count); ++i) {
        uintptr_t at = sigdb::Va(kAnchors[i].va);
        // The analysed build keeps its exact guard bytes; elsewhere the signature already matched.
        if (g_known && at && !GuardMatches(reinterpret_cast<const uint8_t*>(at), kAnchors[i].guard, 16)) at = 0;
        g_resolved[i] = reinterpret_cast<void*>(at);
        g_resolvedAnchors += at != 0;
        if (log && !at) Log("anchor %-24s NOT FOUND in this build (feature off)", kAnchors[i].name);
    }
    bool core = true;
    for (size_t i = 0; i < size_t(Anchor::SkeletonBuild); ++i)
        if (!g_resolved[i]) {
            core = false;
            if (log) Log("core anchor missing: %s", kAnchors[i].name);
        }
    for (uint64_t va : kCoreVas)
        if (!sigdb::Va(va)) {
            core = false;
            if (log) Log("core address missing: recorded 0x%llx", static_cast<unsigned long long>(va));
        }
    return core;
}

