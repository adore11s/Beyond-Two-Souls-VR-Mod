void* ResolveHandle(void* handle) {
    if (!handle) return nullptr;
    const uint32_t flags = Read<uint32_t>(handle, 0x20);
    if ((flags >> 29) & 1) {
        if (void* cached = Read<void*>(handle, 0x30)) return cached;
        using SlowFn = void* (*)(void*);
        auto slow = reinterpret_cast<SlowFn>(Addr(Anchor::KcomResolveSlow));
        return slow ? slow(handle) : nullptr;
    }
    using ResolveFn = void* (*)(void*, int, int);
    auto resolve = reinterpret_cast<ResolveFn>(Addr(Anchor::KcomResolve));
    return resolve ? resolve(handle, 0, 0) : nullptr;
}

bool ObjectName(const void* obj, char* out, size_t cap) {
    if (!out || !cap) return false;
    out[0] = 0;
    __try {
        if (!obj) return false;
        const void* handle = *reinterpret_cast<void* const*>(static_cast<const uint8_t*>(obj) + 0x20);
        if (!handle) return false;
        const char* const* holder = *reinterpret_cast<const char* const* const*>(static_cast<const uint8_t*>(handle) + 0x18);
        if (!holder || !*holder) return false;
        const char* s = *holder;
        size_t i = 0;
        for (; i + 1 < cap && s[i]; ++i) out[i] = s[i];
        out[i] = 0;
        return i > 0;
    } __except (EXCEPTION_EXECUTE_HANDLER) {
        out[0] = 0;
        return false;
    }
}

